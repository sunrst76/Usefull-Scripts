#!/bin/bash
# ===========================================================
# КОНФИГУРАЦИЯ ПУТЕЙ
# ===========================================================
USB_BASE="/run/user/1001/media"
SRC=$(find "$USB_BASE" -type d -name "updates_linux" 2>/dev/null | head -n 1)
DST="/mnt/updates"

# Коды цветов
RED='\033[0;31m'
GREEN='\033[0;32m'
CYAN='\033[0;36m'
YELLOW='\033[1;33m'
NC='\033[0m'

# Проверки путей
if [ -z "$SRC" ]; then
	echo -e "${RED}Ошибка: Исходная папка не найдена в: $USB_BASE!${NC}"
	exit 1
fi
if [ ! -d "$DST" ]; then
	echo -e "${YELLOW}Ошибка: Целевая папка не найдена: $DST${NC}"
	exit 1
fi
echo -e "${CYAN}Синхронизация файлов запущена...${NC}"
echo -e "Проверяются только новые и измененные по размеру файлы.\n"

# ===========================================================
# ЗАПУСК СИНХРОНИЗАЦИИ С ОБЩИМ ПРОГРЕССОМ
# ===========================================================
total_files=$(find "$SRC" -type f | wc -l)
copied_count=0 # сколько файлов реально скопировано
processed_count=0 # общий технический счетчик шагов

# Запускаем высокоскоростное обновление 
# Используем временный файл лога
LOG_FILE=$(mktemp)
cp -ruv "$SRC"/. "$DST/" 2>/dev/null "$LOG_FILE" &
CP_PID=$!

# Пока идет копирование в фоне, рисуем бегущий прогресс-бар
while kill -0 $CP_PID 2>/dev/null; do
copied_count=$(wc -l < "$LOG_FILE")

# защита от деления на 0
[ $total_files -eq 0 ] && percent=100 || percent=$((copied_count *100 / total_files))
# если процент из-за пропуска файлов превысил 100, прижимаем его
[ $percent -gt 100 ] && percent=100 
echo -ne " Синхронизация файлов: [ $percent% ] Обработка данных... \r
sleep 0.2
done

# дожидаемся окончательного закрытия процесса на всякий случай
wait $CP_PID
CP_STATUS=$?

# считываем финальные показатели из лога
copied_count=$(wc -l < "$LOG_FILE")
skipped_count=$((total_files - copied_count))
[ $skipped_count -lt 0 ] && skipped_count=0 # Защита от отрицательных чисел
rm -f "$LOG_FILE" # удаляем временный лог

# вывод финала и статистики
if [ $CP_STATUS -eq 0 ]; then
echo -e "\n\n${GREEN}[УСПЕХ] Синхронизация файлов завершена!${NC}"
echo -e "\n${YELLOW}===========================================${NC}"
echo -e "${YELLOW}*** ИТОГОВАЯ СТАТИСТИКА УСПЕШНА ***${NC}"
echo -e "${YELLOW}===========================================${NC}"
echo -e " Всего файлов на флешке:         ${CYAN}$total_files${NC}"
echo -e " Реально скопировано/обновлено:  ${GREEN}$copied_count${NC}"
echo -e " Пропущено (уже актуальные):  	  ${NС}$skipped_count${NC}"
echo -e "${YELLOW}===========================================${NC}"
else
echo -e "\n\n${RED}[ОШИБКА] Во время синхронизации произошли сбои.${NC}"
fi
echo -e "\n${CYAN}Нажмите клавишу [Enter] для выхода из скрипта...${NC}"
read -r